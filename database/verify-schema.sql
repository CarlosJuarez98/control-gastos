  SELECT 'MESES_RESTANTES' FROM dual UNION ALL
  SELECT 'MONTO_TOTAL' FROM dual UNION ALL
  SELECT 'GASTO_ORIGEN_ID' FROM dual UNION ALL
  SELECT 'SERVICIO_FIJO_COMPARTIDO_ID' FROM dual UNION ALL
  SELECT 'DIA_PAGO' FROM dual
